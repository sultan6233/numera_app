package com.numera.app.features.numbers.domain

/**
 * Personal Year/Month always reduce to a plain 1-9 digit (see AdvancedNumerology), so unlike
 * NumberMeanings there's no master-number case to cover here.
 */
object PersonalCycleMeanings {
    private val yearThemes = mapOf(
        1 to "Год новых начинаний. Время сеять, а не пожинать — решения, принятые сейчас, зададут тон следующим девяти годам.",
        2 to "Год партнёрства и терпения. Результат приходит через сотрудничество, а не через сольный рывок.",
        3 to "Год самовыражения и общения. Хорошее время для творческих проектов и расширения круга общения.",
        4 to "Год фундамента. Дисциплина и системная работа окупятся позже — не время для рискованных прыжков.",
        5 to "Год перемен. Планы меняются, появляются неожиданные возможности — гибкость важнее контроля.",
        6 to "Год ответственности и заботы — о доме, семье, близких отношениях. Возможны важные решения о браке или переезде.",
        7 to "Год внутренней работы. Меньше внешней суеты, больше пересмотра курса и накопления знаний.",
        8 to "Год результата. То, что вы строили годами, может материализоваться — в деньгах, статусе, признании.",
        9 to "Год завершений. Пора отпускать то, что отжило, освобождая место для нового девятилетнего цикла."
    )

    private val monthThemes = mapOf(
        1 to "Начните то, что откладывали — месяц благоволит первому шагу.",
        2 to "Месяц для диалога и партнёрства, не для сольных решений.",
        3 to "Хорошее время для самовыражения — от важного разговора до творческого проекта.",
        4 to "Сфокусируйтесь на порядке и рутинных задачах, которые давно ждали.",
        5 to "Будьте готовы к переменам в планах — не держитесь за один сценарий.",
        6 to "В фокусе — дом и близкие отношения.",
        7 to "Месяц для паузы и анализа, не для новых обязательств.",
        8 to "Время подводить итоги усилий и говорить о деньгах и статусе прямо.",
        9 to "Заканчивайте начатое — месяц на завершение, не на старт нового."
    )

    fun yearTheme(personalYear: Int): String = yearThemes[personalYear] ?: yearThemes.getValue(9)
    fun monthTheme(personalMonth: Int): String = monthThemes[personalMonth] ?: monthThemes.getValue(9)
}
